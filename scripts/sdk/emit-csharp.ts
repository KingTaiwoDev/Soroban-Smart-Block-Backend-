/** Format a raw schema property name into a safe PascalCase C# property name. */
export function toPascalCase(name: string): string {
  const parts = name
    .replace(/[^A-Za-z0-9_]/g, '_')
    .split('_')
    .filter((p) => p.length > 0);
  if (parts.length === 0) return 'Property';
  const pascal = parts.map((p) => p.charAt(0).toUpperCase() + p.slice(1)).join('');
  return /^[0-9]/.test(pascal) ? `P_${pascal}` : pascal;
}

/** Sanitize an identifier to ensure it does not conflict with C# keywords or enclosing types. */
export function sanitizePropertyName(propName: string, enclosingTypeName: string): string {
  let name = toPascalCase(propName);
  if (name === enclosingTypeName) {
    name = `${name}Value`;
  }
  if (CSHARP_KEYWORDS.has(name.toLowerCase())) {
    name = `@${name}`;
  }
  return name;
}

/** Resolve C# type representation for a JSON schema. */
function csharpType(
  schema: JsonSchema | null | undefined,
  known: Set<string>,
  depth = 0,
): string {
  if (!schema || depth > 5) return 'object';

  if (typeof schema.$ref === 'string') {
    const match = /^#\/components\/schemas\/(.+)$/.exec(schema.$ref);
    return match && known.has(match[1]) ? modelName(match[1]) : 'object';
  }

  if (schema.oneOf || schema.anyOf) {
    const variants = (schema.oneOf ?? schema.anyOf ?? []).map((s) => csharpType(s, known, depth + 1));
    const unique = Array.from(new Set(variants));
    return unique.length === 1 ? unique[0] : 'object';
  }

  if (schema.allOf) {
    return schema.allOf.length === 1 ? csharpType(schema.allOf[0], known, depth + 1) : 'Dictionary<string, object>';
  }

  const type = Array.isArray(schema.type) ? schema.type[0] : schema.type;
  switch (type) {
    case 'string':
      return 'string';
    case 'integer':
      return schema.format === 'int32' ? 'int' : 'long';
    case 'number':
      return 'double';
    case 'boolean':
      return 'bool';
    case 'array': {
      const itemType = csharpType(schema.items, known, depth + 1);
      return `List<${itemType}>`;
    }
    case 'object':
      return 'Dictionary<string, object>';
    default:
      return schema.properties ? 'Dictionary<string, object>' : 'object';
  }
}

/** Emit strongly typed C# record models. */
export function emitCSharpModels(doc: OpenApiDocument): string {
  const schemas = doc.components?.schemas ?? {};
  const known = new Set(Object.keys(schemas));

  const modelBlocks = Object.keys(schemas)
    .sort()
    .map((rawName) => {
      const className = modelName(rawName);
      const s = schemas[rawName];

      if (s.properties && Object.keys(s.properties).length > 0) {
        const propLines = Object.keys(s.properties)
          .sort()
          .map((propKey) => {
            const propSchema = s.properties![propKey];
            const baseType = csharpType(propSchema, known);
            const isNullable = propSchema.nullable === true || (!propSchema.required && baseType !== 'object');
            const typeStr = isNullable && !baseType.endsWith('?') ? `${baseType}?` : baseType;
            const propIdentifier = sanitizePropertyName(propKey, className);

            return `        [JsonPropertyName(${JSON.stringify(propKey)})]\n        public ${typeStr} ${propIdentifier} { get; init; }`;
          });

        return `    /// <summary>
    /// Model for ${className}
    /// </summary>
    public record ${className}
    {
${propLines.join('\n\n')}
    }`;
      }

      const aliasType = csharpType(s, known);
      return `    /// <summary>
    /// Model for ${className}
    /// </summary>
    public record ${className}
    {
        [JsonPropertyName("value")]
        public ${aliasType}? Value { get; init; }
    }`;
    });

  return `${HEADER}
namespace SorobanExplorer.Client;

using System;
using System.Collections.Generic;
using System.Text.Json.Serialization;

${modelBlocks.join('\n\n')}
`;
}

/** Emit C# operations metadata table. */
export function emitCSharpOperations(doc: OpenApiDocument, ops: NormalizedOperation[], fingerprint: string): string {
  const sortedOps = [...ops].sort((a, b) => a.id.localeCompare(b.id));

  const opEntries = sortedOps.map((op) => {
    const pathParams = op.params
      .filter((p) => p.in === 'path')
      .map((p) => JSON.stringify(p.name));

    const queryParams = op.params
      .filter((p) => p.in === 'query')
      .map((p) => {
        return `                new QueryParamMetadata { Name = ${JSON.stringify(p.name)}, Type = ${JSON.stringify(p.type)}, Required = ${p.required ? 'true' : 'false'} }`;
      });

    const bodyType = op.body ? (op.body.required ? 'required' : 'optional') : 'none';
    const contentType = op.body?.contentType ? JSON.stringify(op.body.contentType) : 'null';
    const summary = op.summary ? JSON.stringify(op.summary) : 'null';

    return `            [${JSON.stringify(op.id)}] = new OperationMetadata
            {
                Id = ${JSON.stringify(op.id)},
                Method = ${JSON.stringify(op.method.toUpperCase())},
                Path = ${JSON.stringify(op.path)},
                PathParams = new string[] { ${pathParams.join(', ')} },
                QueryParams = new QueryParamMetadata[]
                {
${queryParams.join(',\n')}
                },
                BodyType = ${JSON.stringify(bodyType)},
                ContentType = ${contentType},
                Deprecated = ${op.deprecated ? 'true' : 'false'},
                Summary = ${summary}
            }`;
  });

  return `${HEADER}
namespace SorobanExplorer.Client;

using System;
using System.Collections.Generic;

/// <summary>
/// Static metadata and registry for every operation in the Soroban Explorer OpenAPI spec.
/// </summary>
public static class Operations
{
    public const string SpecVersion = ${JSON.stringify(doc.info?.version ?? '0.0.0')};
    public const string SpecFingerprint = ${JSON.stringify(fingerprint)};
    public const int OperationCount = ${ops.length};

    public static readonly IReadOnlyDictionary<string, OperationMetadata> All = new Dictionary<string, OperationMetadata>
    {
${opEntries.join(',\n')}
    };
}

public record QueryParamMetadata
{
    public string Name { get; init; } = "";
    public string Type { get; init; } = "";
    public bool Required { get; init; }
}

public record OperationMetadata
{
    public string Id { get; init; } = "";
    public string Method { get; init; } = "";
    public string Path { get; init; } = "";
    public IReadOnlyList<string> PathParams { get; init; } = Array.Empty<string>();
    public IReadOnlyList<QueryParamMetadata> QueryParams { get; init; } = Array.Empty<QueryParamMetadata>();
    public string BodyType { get; init; } = "none";
    public string? ContentType { get; init; }
    public bool Deprecated { get; init; }
    public string? Summary { get; init; }
}
`;
}

